package com.lostfound

import com.lostfound.model.FoundItem
import com.lostfound.model.LostItem

/**
 * ============================================================
 * SEARCH ITEM
 * ============================================================
 *
 * Common model used by the Search module.
 *
 * Search displays both:
 *
 *  - Lost items
 *  - Found items
 *
 * LostItem and FoundItem have different field names
 * for location/date, so they are converted into this
 * common SearchItem model.
 *
 * ownerId is used to determine who uploaded the item.
 *
 * Example:
 *
 * Item uploaded by User ID 1:
 *
 * ownerId = 1
 *
 * If logged-in user ID = 1:
 *
 * Request Claim -> DISABLED
 *
 * If logged-in user ID = 2:
 *
 * Request Claim -> ENABLED
 *
 * ============================================================
 */
data class SearchItem(

    // ============================================================
    // ITEM ID
    // ============================================================

    val id: Long,


    // ============================================================
    // ITEM NAME
    // ============================================================

    val itemName: String,


    // ============================================================
    // CATEGORY
    // ============================================================

    val category: String,


    // ============================================================
    // COLOR
    // ============================================================

    val color: String?,


    // ============================================================
    // LOCATION
    // ============================================================

    val location: String,


    // ============================================================
    // DATE
    // ============================================================

    val date: String,


    // ============================================================
    // IMAGE URL
    // ============================================================

    val imageUrl: String?,


    // ============================================================
    // ITEM TYPE
    // ============================================================
    //
    // LOST or FOUND
    //
    // ============================================================

    val type: String,


    // ============================================================
    // OWNER / UPLOADER ID
    // ============================================================
    //
    // This is the user ID of the person who uploaded the item.
    //
    // Example:
    //
    // User ID 1 uploads Mobile
    //
    // ownerId = 1
    //
    // This value is used by the Claim button.
    //
    // If:
    //
    // ownerId == current logged-in user ID
    //
    // Request Claim button will be disabled.
    //
    // Otherwise:
    //
    // Request Claim button will be enabled.
    //
    // Nullable so older/backend records can be handled safely.
    //
    // ============================================================

    val ownerId: Long?

) {

    companion object {

        // ============================================================
        // CONVERT LOST ITEM -> SEARCH ITEM
        // ============================================================

        fun fromLostItem(
            item: LostItem
        ): SearchItem {

            return SearchItem(

                // ----------------------------------------------------
                // Item ID
                // ----------------------------------------------------

                id = item.id,


                // ----------------------------------------------------
                // Item name
                // ----------------------------------------------------

                itemName = item.itemName,


                // ----------------------------------------------------
                // Category
                // ----------------------------------------------------

                category = item.category,


                // ----------------------------------------------------
                // Color
                // ----------------------------------------------------

                color = item.color,


                // ----------------------------------------------------
                // Lost location
                // ----------------------------------------------------

                location = item.locationLost,


                // ----------------------------------------------------
                // Lost date
                // ----------------------------------------------------

                date = item.dateLost,


                // ----------------------------------------------------
                // Image
                // ----------------------------------------------------

                imageUrl = item.imageUrl,


                // ----------------------------------------------------
                // Type
                // ----------------------------------------------------

                type = "LOST",


                // ----------------------------------------------------
                // Owner / uploader
                // ----------------------------------------------------

                ownerId = item.ownerId
            )
        }


        // ============================================================
        // CONVERT FOUND ITEM -> SEARCH ITEM
        // ============================================================

        fun fromFoundItem(
            item: FoundItem
        ): SearchItem {

            return SearchItem(

                // ----------------------------------------------------
                // Item ID
                // ----------------------------------------------------

                id = item.id,


                // ----------------------------------------------------
                // Item name
                // ----------------------------------------------------

                itemName = item.itemName,


                // ----------------------------------------------------
                // Category
                // ----------------------------------------------------

                category = item.category,


                // ----------------------------------------------------
                // Color
                // ----------------------------------------------------

                color = item.color,


                // ----------------------------------------------------
                // Found location
                // ----------------------------------------------------

                location = item.locationFound,


                // ----------------------------------------------------
                // Found date
                // ----------------------------------------------------

                date = item.dateFound,


                // ----------------------------------------------------
                // Image
                // ----------------------------------------------------

                imageUrl = item.imageUrl,


                // ----------------------------------------------------
                // Type
                // ----------------------------------------------------

                type = "FOUND",


                // ----------------------------------------------------
                // Owner / uploader
                // ----------------------------------------------------

                ownerId = item.ownerId
            )
        }
    }
}